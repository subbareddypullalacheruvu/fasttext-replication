"""
make_numbers.py - write report/numbers.tex from results/*.json, so every number in the
report comes from the results files and cannot drift out of sync with them.

    python report/make_numbers.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
R = json.load(open(RES / "results.json"))
S = json.load(open(RES / "20ng_epoch_sweep.json"))
J = RES / "llm_judge" / "summary.json"
NAMES = {"1": "World", "2": "Sports", "3": "Business", "4": "SciTech"}

macros = {}


def put(name, value, fmt="{:.2f}"):
    macros[name] = fmt.format(value) if isinstance(value, float) else str(value)


def mean_recall(entry, cls):
    rs = [r["per_class_recall"][cls] for r in entry["runs"]]
    return 100 * sum(rs) / len(rs)


for key, tag in [("ag_news_bigram", "AGbi"), ("ag_news_unigram", "AGuni"),
                 ("20ng_paper_cfg", "NGpaper"), ("20ng_epoch25", "NGep"),
                 ("20ng_epoch25_hs", "NGhs"), ("rss2026_paper_cfg", "RSSin")]:
    e = R[key]
    put(tag, e["acc_mean"]); put(tag + "SD", e["acc_sd"])
    put(tag + "Min", e["acc_min"]); put(tag + "Max", e["acc_max"])
    put(tag + "T", e["train_s_mean"], "{:.1f}"); put(tag + "Fone", e["macro_f1_mean"], "{:.1f}")

for key, tag in [("ag_news_tfidf_lr", "AGtf"), ("20ng_tfidf_lr", "NGtf"), ("rss2026_tfidf_lr", "RSStf")]:
    if key in R:
        put(tag, R[key]["acc_mean"]); put(tag + "T", R[key]["train_s_mean"], "{:.1f}")
        put(tag + "Fone", R[key]["macro_f1_mean"], "{:.1f}")

put("AGgap", R["ag_news_bigram"]["acc_mean"] - 92.5, "{:+.2f}")
put("AGtfGap", R["ag_news_tfidf_lr"]["acc_mean"] - R["ag_news_bigram"]["acc_mean"], "{:.2f}")
put("AGperEpoch", R["ag_news_bigram"]["train_s_mean"] / 5, "{:.1f}")
put("AGuniGap", R["ag_news_unigram"]["acc_mean"] - 91.5, "{:+.2f}")
put("AGbigramGain", R["ag_news_bigram"]["acc_mean"] - R["ag_news_unigram"]["acc_mean"], "{:.1f}")
put("AGspeedup", R["ag_news_tfidf_lr"]["train_s_mean"] / R["ag_news_bigram"]["train_s_mean"], "{:.0f}")
put("NGspeedup", R["20ng_tfidf_lr"]["train_s_mean"] / R["20ng_epoch25"]["train_s_mean"], "{:.0f}")
for c, n in NAMES.items():
    put("AGrec" + n, mean_recall(R["ag_news_bigram"], c), "{:.1f}")

best = max(S, key=lambda s: s["acc_mean"])
put("NGbest", best["acc_mean"]); put("NGbestSD", best["acc_sd"])
put("NGbestEp", best["epoch"], "{}"); put("NGbestLr", best["lr"], "{}")
put("NGbestT", best["train_s"], "{:.1f}")
put("NGbestGap", R["20ng_tfidf_lr"]["acc_mean"] - best["acc_mean"], "{:.1f}")

D = json.load(open(RES / "20ng_dim_sweep.json"))
for r in D:
    tag = ("DimA" if r["epoch"] == 25 else "DimB") + {10: "x", 50: "l", 100: "c"}[r["dim"]]
    put(tag, r["acc_mean"]); put(tag + "T", r["train_s"], "{:.1f}")
put("DimMaxChange", max(abs(r["acc_mean"] - next(q["acc_mean"] for q in D if q["epoch"] == r["epoch"] and q["dim"] == 10)) for r in D), "{:.1f}")

x = R["agnews_to_rss2026"]
put("XF", x["acc_mean"]); put("XFSD", x["acc_sd"]); put("XFn", x["n_test"], "{}")
put("XFdrop", R["ag_news_bigram"]["acc_mean"] - x["acc_mean"], "{:.1f}")
for c, n in NAMES.items():
    put("XFrec" + n, 100 * sum(r["per_class_recall"][c] for r in x["runs"]) / len(x["runs"]), "{:.1f}")

if J.exists():
    j = json.load(open(J))
    put("JudgeN", j["n_errors_judged"], "{}")
    for v, n in [("MODEL_ERROR", "Model"), ("AMBIGUOUS", "Amb"), ("LABEL_NOISE", "Noise")]:
        put("Judge" + n, j["verdicts"][v], "{}"); put("Judge" + n + "Pct", j["verdict_pct"][v], "{:.0f}")
    # accuracy of the judged run (seed 0) if non-model errors are set aside
    # use the judged run itself (llm_judge/judged_predictions_seed0.tsv), not results.json:
    # multi-threaded fastText is not bit-reproducible, so a rerun changes seed 0
    n = x["n_test"]
    correct = n - j["n_errors_judged"]
    acc0 = 100 * correct / n
    noise, amb = j["verdicts"]["LABEL_NOISE"], j["verdicts"]["AMBIGUOUS"]
    put("XFseedZero", acc0)
    put("XFnoNoise", 100 * correct / (n - noise), "{:.1f}")            # drop noisy items
    put("XFlenient", 100 * (correct + amb) / (n - noise), "{:.1f}")   # also accept ambiguous
    hc = j["human_check"]
    if isinstance(hc, dict):
        put("HumanN", hc["n"], "{}"); put("HumanAgree", hc["raw_agreement_pct"], "{:.0f}")
        put("HumanKappa", hc["cohen_kappa"], "{:.2f}"); put("HumanBinary", hc["binary_agreement_pct"], "{:.0f}")
    else:  # shows up in bold red in the PDF until the human check is done
        for k in ["HumanN", "HumanAgree", "HumanKappa", "HumanBinary"]:
            macros[k] = r"\textcolor{red}{\textbf{TODO}}"

out = ["% generated by report/make_numbers.py - do not edit by hand"]
out += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
(ROOT / "report" / "numbers.tex").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {len(macros)} macros to report/numbers.tex")
